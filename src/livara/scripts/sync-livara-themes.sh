          printf "\n[%s]\ntheme='Livara.json'\n" "$foliate_keyfile_section" >> "$keyfile.tmp.$$"
        fi
        mv -f "$keyfile.tmp.$$" "$keyfile"
        chmod 0644 "$keyfile"
        log "Foliate Flatpak reader theme selected: Livara.json"
