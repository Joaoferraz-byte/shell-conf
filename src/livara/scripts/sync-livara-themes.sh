    hex_to_rgb() {
      local hex="${1#\#}"
      [[ "${#hex}" == 6 ]] || hex=000000
      printf '%d %d %d' "0x${hex:0:2}" "0x${hex:2:2}" "0x${hex:4:2}"
    }

    hex_to_argb_decimal() {
      local hex="${1#\#}"
      [[ "${#hex}" == 6 ]] || hex=000000
      printf '%u' "$((16#FF${hex}))"
    }

    write_atomic() {
      local target="$1"
